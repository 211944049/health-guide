/**
 * 专题聚合页配置。
 *
 * 专题与分类的区别（这个区别决定了本文件的存在）：
 *   · **分类**（食/衣/住/行/身心/健康管理）是内容的**归档方式**，一条词条只属于一个分类。
 *   · **专题**是读者的**进入方式**，按处境组织，一条词条可以出现在多个专题里。
 *   `/browse/` 负责前者，专题负责后者。所以专题不是把分类抄一遍。
 *
 * 选题依据（来自 `run.cmd clusters` → `scripts/analyze-clusters.mjs`）：
 *   1. **受众词频**：69 条词条里「上班族」出现 35 次、「中老年人」26 次、
 *      「有婴幼儿的家庭」17 次、「学生」15 次、「跑步爱好者」11 次 —— 这些是真实的读者群像。
 *   2. **跨分类枢纽**：`什么时候该看医生` 连接 5 个分类、`失眠怎么办` 连接 4 个 ——
 *      从这类枢纽两跳扩张能覆盖 25–29 条词条，足够撑起一个专题。
 *
 * 每个专题的 `intro` 说明**为什么这样组织**，`steps` 是建议阅读顺序
 * （先读什么、再读什么，以及为什么这个顺序）。**顺序是这个页面的核心价值**——
 * 单纯罗列词条的话，/browse/ 已经做了。
 *
 * `check-topics.mjs` 会校验：slug 都存在、条数不少于 6、不重复、
 * 且每个专题至少跨 3 个分类（否则它就只是分类的复制品）。
 */

