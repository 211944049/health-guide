/** 组装一个词条文件。summary 含 * 时必须整体单引号（YAML 规则）。 */
function build({ slug, title, category, evidence, cost, time, audience, summary, sources, related, tags, body }) {
  // summary 里有 * 或以特殊字符开头 → 用单引号包裹并把内部单引号转义
  const quoted = `'${summary.replace(/'/g, "''")}'`;
  const fm = [
    '---',
    `title: ${title}`,
    `category: ${category}`,
    `evidence: ${evidence}`,
    `cost: ${cost}`,
    `time: ${time}`,
    'audience:',
    ...audience.map((a) => `  - ${a}`),
    `updated: ${TODAY}`,
    `review_after: ${reviewAfter(evidence)}`,
    'status: 完整',
    'related:',
    ...related.map((r) => `  - ${r}`),
    `summary: ${quoted}`,
    'sources:',
    ...sources.map((s) => `  - ${JSON.stringify(s)}`),
    'tags:',
    ...tags.map((t) => `  - ${t}`),
    '---',
    '',
  ].join('\n');
  return `${fm}${body.trim()}\n`;
}

/** 复审期：A/B 6 个月，C 4 个月，D 3 个月（与全站策略一致）。 */
function reviewAfter(evidence) {
  const months = { A: 6, B: 6, C: 4, D: 3 }[evidence] ?? 6;
  const d = new Date(`${TODAY}T00:00:00Z`);
  d.setUTCMonth(d.getUTCMonth() + months);
  return d.toISOString().slice(0, 10);
}

